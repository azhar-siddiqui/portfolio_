/** Look up a simple-icons entry by slug (e.g. `"react"`, `"nextdotjs"`). */
export function getSimpleIcon(slug: string): SimpleIconData | null {
  return SLUG_MAP[slug.toLowerCase()] ?? null;
}

/** Look up by export-style key (e.g. `"siGithub"`, `"siX"`). */
export function getSimpleIconByKey(key: string): SimpleIconData | null {
  const slug = key.startsWith("si") ? key.slice(2) : key;
  return getSimpleIcon(slug.charAt(0).toLowerCase() + slug.slice(1));
}